import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
const U='file:///home/claude/patch/dist/CRM_Tracker_Dashboard.html';
const MOCK='http://mock.test/api/ask';
const b=await chromium.launch(); const ctx=await b.newContext({viewport:{width:1300,height:900}}); const p=await ctx.newPage();
const errs=[]; p.on('pageerror',e=>errs.push(e.message.slice(0,200)));
let mode='normal', hits=0;
// scripted "model": picks a tool from keywords, then writes an answer from the tool result
await p.route(MOCK, async (route)=>{
  hits++;
  const req=route.request();
  if(req.method()==='OPTIONS') return route.fulfill({status:204,headers:{'access-control-allow-origin':'*','access-control-allow-headers':'content-type'}});
  const H={'access-control-allow-origin':'*','content-type':'application/json'};
  if(mode==='down') return route.abort();
  if(mode==='429') return route.fulfill({status:429,headers:H,body:JSON.stringify({error:'rate_limited'})});
  const {messages}=JSON.parse(req.postData()); const last=messages[messages.length-1];
  const q=messages[0].content.toLowerCase();
  const call=(name,args)=>route.fulfill({status:200,headers:H,body:JSON.stringify({message:{role:'assistant',content:null,tool_calls:[{id:'c'+hits,type:'function',function:{name,arguments:JSON.stringify(args)}}]}})});
  const say=(t)=>route.fulfill({status:200,headers:H,body:JSON.stringify({message:{role:'assistant',content:t}})});
  if(last.role==='tool'){
    const r=JSON.parse(last.content);
    if(mode==='hallucinate') return say('Dealer App had 777 valid orders worth ₹99,99,999.');
    if(r.status!=='ok') return say('Currently no such data is present in the dashboard. '+(r.reason||''));
    if(r.dealer_app) return say(`Between ${r.period}, the Dealer App had ${r.dealer_app.valid} valid orders worth ${r.dealer_app.order_value.display} and DataSense had ${r.datasense.valid} valid orders worth ${r.datasense.order_value.display} (${r.scope}).`);
    if(r.total!==undefined&&r.by_platform) return say(`The tracker has ${r.total} issues: ${r.open} open, ${r.resolved} resolved, ${r.overdue} overdue (${r.period}).`);
    if(r.orders_recorded!==undefined) return say(`${r.period}: ${r.orders_recorded} orders were recorded, ${r.sfa_app_orders} on the SFA app (${r.sfa_share}).`);
    if(r.bizom) return say(`${r.period}: Bizom had ${r.bizom.active_users} active users and DataSense ${r.datasense.active_employees} active employees; ${r.people_in_both_systems} people appear in both.`);
    if(r.by_month&&r.metric) return say(`${r.metric} by month is in the figures below (${r.period}).`);
    if(r.items) return say(`Top ${r.items.length}: ${r.items.map(i=>i.name+' '+i.order_value.full).join('; ')} (${r.period}).`);
    if(r.total&&r.top_categories) return say(`${r.total} complaints, ${r.not_closed} not closed (${r.period}).`);
    return say('See the figures below.');
  }
  if(/weather|capital|cricket/.test(q)) return say('It is sunny today.');
  if(/profit|margin/.test(q)) return call('get_dealer_app_vs_datasense',{dealer:'Nobody Traders'});
  if(/issue|overdue|tracker/.test(q)) return call('get_issues',{});
  if(/usage report|sfa share|punched/.test(q)) return call('get_usage_report',{});
  if(/bizom/.test(q)) return call('get_bizom_vs_datasense',{});
  if(/trend/.test(q)) return call('get_trends',{metric:'valid_orders'});
  if(/model|sku/.test(q)) return call('get_models',{kind:'model',rank_by:'value',limit:3});
  if(/complaint/.test(q)) return call('get_complaints',{system:'datasense'});
  if(/jitesh/.test(q)) return call('get_dealer_app_vs_datasense',{dealer:'Jitesh Traders'});
  return call('get_dealer_app_vs_datasense',{});
});
await p.goto(U); await p.waitForTimeout(7000);
await p.evaluate((u)=>localStorage.setItem('askApiUrl',u),MOCK);
await p.reload(); await p.waitForTimeout(6000);
