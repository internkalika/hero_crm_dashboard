// Recovers the data of the deployed CRM_Tracker_Dashboard (the single index.html) so that the rebuilt app can be
// loaded with exactly the same datasets:
//   node scripts/extract-from-deployed.mjs [path/to/deployed/index.html]
// Writes src/generated/snapshot.data.ts (the 17 embedded datasets + their label) and src/generated/usage.data.ts
// (the DataSense Usage Report payload). Both are git-ignored: they hold business data.
import fs from 'node:fs';
import zlib from 'node:zlib';

const from = process.argv[2] ?? new URL('../../index.html', import.meta.url).pathname;
const html = fs.readFileSync(from, 'utf8');
const gen = (f) => new URL(`../src/generated/${f}`, import.meta.url);

const snap = html.match(/const \w+=\{info:\{label:("(?:[^"\\]|\\.)*")\},b64:"([A-Za-z0-9+/=]+)"\};/);
if (!snap) throw new Error('embedded snapshot not found in ' + from);
const label = JSON.parse(snap[1]);
const payloads = JSON.parse(zlib.gunzipSync(Buffer.from(snap[2], 'base64')).toString('utf8'));
const info = { label, builtAt: payloads.map((p) => p.meta.importedAt).sort().pop(), datasets: payloads.length };
fs.writeFileSync(
  gen('snapshot.data.ts'),
  `// GENERATED by scripts/extract-from-deployed.mjs - contains business data, never commit.\nimport type { SnapshotBundle } from '../lib/store/snapshot';\n\nexport const SNAPSHOT: SnapshotBundle | null = {\n  info: ${JSON.stringify(info)},\n  b64: '${snap[2]}',\n};\n`,
);
console.log(`snapshot: "${label}" - ${payloads.length} datasets`);

const usage = html.match(/const __UREP_B64="([A-Za-z0-9+/=]+)";/);
if (!usage) throw new Error('usage report payload not found');
JSON.parse(zlib.gunzipSync(Buffer.from(usage[1], 'base64')).toString('utf8'));
fs.writeFileSync(gen('usage.data.ts'), `// GENERATED by scripts/extract-from-deployed.mjs - contains business data, never commit.\nexport const USAGE_REPORT: string | null = '${usage[1]}';\n`);
console.log(`usage report: ${(usage[1].length / 1e3).toFixed(0)} kB base64`);
