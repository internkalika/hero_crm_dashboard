// Builds the data snapshot that is embedded in the single-file HTML dashboard.
//   npm run snapshot                     reads ./data/CRM MIS
//   CRM_MIS_DIR=/path/to/files npm run snapshot
// It runs the same readers and normalisers as the app, keeps meta + records + issues of every file, drops the raw
// source rows (smaller file, and unmasked mobile numbers never leave the source files), then gzips and base64-encodes.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import type { DatasetPayload } from '../src/lib/types';
import { analyzeInput, normalizeFile } from '../src/lib/ingest/pipeline';
import { fDate } from '../src/lib/export/format';

const dir = process.env.CRM_MIS_DIR ?? path.resolve(__dirname, '../data/CRM MIS');
const out = path.resolve(__dirname, '../src/generated/snapshot.data.ts');
if (!fs.existsSync(dir)) {
  console.error(`Folder not found: ${dir}\nPut the MIS files in data/CRM MIS or set CRM_MIS_DIR.`);
  process.exit(1);
}

const now = new Date();
const payloads: DatasetPayload[] = [];
for (const name of fs.readdirSync(dir).sort()) {
  if (name.startsWith('.') || !/\.(csv|xlsx|xls)$/i.test(name)) continue;
  const buf = fs.readFileSync(path.join(dir, name));
  const buffer = buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength) as ArrayBuffer;
  const { analysis, read } = analyzeInput({ name, size: buf.byteLength, buffer }, name);
  const source = analysis.identification.source;
  if (!read || !source || analysis.identification.ambiguous) {
    console.warn(`skipped (not identified): ${name}`);
    continue;
  }
  const p = normalizeFile(read, source, { now });
  p.meta.extra = { ...(p.meta.extra ?? {}), fileHash: analysis.hash };
  p.meta.importedAt = now.toISOString();
  payloads.push({ meta: p.meta, records: p.records, issues: p.issues, raw: [] });
  console.log(`ok  ${source.padEnd(22)} ${name}  (${p.records.length} records)`);
}
if (!payloads.length) {
  console.error('No file could be identified; nothing written.');
  process.exit(1);
}

const json = JSON.stringify(payloads);
const gz = zlib.gzipSync(Buffer.from(json), { level: 9 });
const b64 = gz.toString('base64');
const info = { label: `MIS files as supplied, packaged ${fDate(now.toISOString().slice(0, 10))}`, builtAt: now.toISOString(), datasets: payloads.length };
fs.writeFileSync(
  out,
  `// GENERATED by scripts/make-snapshot.ts - contains business data, never commit.\nimport type { SnapshotBundle } from '../lib/store/snapshot';\n\nexport const SNAPSHOT: SnapshotBundle | null = {\n  info: ${JSON.stringify(info)},\n  b64: '${b64}',\n};\n`,
);
console.log(`\n${payloads.length} datasets, ${(json.length / 1e6).toFixed(1)} MB JSON -> ${(gz.length / 1e6).toFixed(2)} MB gzip -> ${out}`);
